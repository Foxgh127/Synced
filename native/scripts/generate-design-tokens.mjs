import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const tokenDirectory = new URL("./src/design/tokens/", root);
const generatedCssUrl = new URL("./src/design/tokens.css", root);
const generatedMotionCssUrl = new URL("./src/design/motion.css", root);
const generatedMotionTsUrl = new URL(
  "./src/design/motion.generated.ts",
  root,
);
const check = process.argv.includes("--check");

function readJson(name) {
  return JSON.parse(
    readFileSync(new URL(name, tokenDirectory), "utf8"),
  );
}

function generatedHeader(source) {
  return `/* Generated by scripts/generate-design-tokens.mjs from ${source}. Do not edit. */`;
}

function renderVariables(entries) {
  return Object.entries(entries)
    .map(([name, value]) => `  --${name}: ${value};`)
    .join("\n");
}

const tokenSources = [
  "global.json",
  "semantic.json",
  "component.json",
  "palette.json",
  "supplemental.json",
];
const variables = Object.assign(
  {},
  ...tokenSources.map((name) => readJson(name).variables),
);
const motion = readJson("motion.json");
const durationVariables = {
  "dur-instant": `${motion.durations.instant}ms`,
  "dur-micro": `${motion.durations.micro}ms`,
  "dur-control": `${motion.durations.control}ms`,
  "dur-panel": `${motion.durations.panel}ms`,
  "dur-view": `${motion.durations.view}ms`,
  "dur-immersive": `${motion.durations.immersive}ms`,
  "dur-ambient": `${motion.durations.ambient}ms`,
  "dur-celebration": `${motion.durations.celebration}ms`,
  "dur-1": `${motion.durations.instant}ms`,
  "dur-2": `${motion.durations.micro}ms`,
  "dur-3": `${motion.durations.control}ms`,
  "dur-4": `${motion.durations.panel}ms`,
  "dur-5": `${motion.durations.view}ms`,
  "dur-6": `${motion.durations.celebration}ms`,
  "ease-out": motion.easings.out,
  "ease-in": motion.easings.in,
  "ease-inout": motion.easings.inout,
  "ease-emphasis": motion.easings.emphasis,
  "ease-spring": motion.easings.spring
};

const tokenCss = `${generatedHeader(tokenSources.join(", "))}
:root {
  color-scheme: dark;
${renderVariables(variables)}
}
`;

const motionCss = `${generatedHeader("tokens/motion.json")}
:root {
${renderVariables(durationVariables)}
}
`;

const motionTs = `${generatedHeader("tokens/motion.json")}
export const DUR = ${JSON.stringify(
  {
    instant: motion.durations.instant,
    fast: motion.durations.micro,
    base: motion.durations.control,
    slow: motion.durations.panel,
    view: motion.durations.view,
    immersive: motion.durations.immersive,
    ambient: motion.durations.ambient,
    brand: motion.durations.celebration
  },
  null,
  2,
)} as const;

export const EASE = ${JSON.stringify(motion.easings, null, 2)} as const;
export const EXIT_RATIO = ${motion.exitRatio};
export const STAGGER_STEP_MS = ${motion.staggerStepMs};
export const STAGGER_MAX_ITEMS = ${motion.staggerMaxItems};
export const IDLE_HIDE_MS = ${motion.idleHideMs};
export const DANMAKU_SPEED_PX_S = ${motion.danmakuSpeedPxS};
export const DANMAKU_LANE_GAP_PX = ${motion.danmakuLaneGapPx};
`;

const outputs = [
  [generatedCssUrl, tokenCss],
  [generatedMotionCssUrl, motionCss],
  [generatedMotionTsUrl, motionTs],
];

let stale = false;
for (const [url, content] of outputs) {
  const path = fileURLToPath(url);
  if (check) {
    let current = "";
    try {
      current = readFileSync(url, "utf8");
    } catch {
      // A missing generated file is stale by definition.
    }
    if (current !== content) {
      stale = true;
      console.error(`${path} is stale; run npm run design:generate`);
    }
  } else {
    writeFileSync(url, content, "utf8");
    console.log(`generated ${path}`);
  }
}

if (stale) process.exitCode = 1;
